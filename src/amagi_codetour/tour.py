"""Build, read and write CodeTour files (schema: https://aka.ms/codetour-schema)."""

from __future__ import annotations

import json
import posixpath
import re
from pathlib import Path

from .anchors import pattern_for

SCHEMA_URL = "https://aka.ms/codetour-schema"


def slugify(text: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return s or "tour"


def _short(path: str) -> str:
    return posixpath.basename(path)


def _names(names, limit=4):
    names = [n for n in names if n not in {"default", "*"}]
    shown = ", ".join(f"`{n}`" for n in names[:limit])
    if len(names) > limit:
        shown += f" and {len(names) - limit} more"
    return shown


def static_description(pick, index: int, total: int) -> str:
    parts = []
    if pick.dist == 0 or index == 0 and pick.entry_reason:
        parts.append(f"**Start here.** This is the entry point: {pick.entry_reason}.")
    if pick.summary:
        parts.append(f"> {pick.summary}")
    anchor = f"The cursor is on {pick.anchor_why}" if pick.anchor_why else ""
    if anchor:
        parts.append(anchor + ".")
    defs = [s.name for s in pick.symbols if s.kind != "method" and not s.name.startswith("_")]
    if defs:
        parts.append(f"Defines {_names(defs, 6)}.")
    if pick.imports:
        bits = []
        for dst, names in pick.imports[:5]:
            shown = _names(names, 3)
            bits.append(f"`{_short(dst)}`" + (f" ({shown})" if shown else ""))
        parts.append("Calls into " + ", ".join(bits) + " (later in this tour).")
    if pick.used_by:
        parts.append("Used by " + ", ".join(f"`{_short(p)}`" for p in pick.used_by[:5]) + ".")
    parts.append(f"_{pick.n_lines} lines._")
    return "\n\n".join(parts)


def readme_step(plan, repo=None) -> dict:
    langs = ", ".join(plan.languages) if plan.languages else "no recognised source"
    entry = plan.picks[0].path if plan.picks else ""
    text = (
        f"Welcome to **{plan.name}**. Start with the README for what the project is for.\n\n"
        f"This tour walks through {len(plan.picks)} files in reading order"
        + (f", starting at the entry point `{entry}`" if entry else "")
        + f". Languages found: {langs}."
    )
    if repo is None:
        return {"file": plan.readme, "line": 1, "title": "Overview", "description": text}
    lines = repo.read(plan.readme) or []
    first = next((i for i, t in enumerate(lines, 1) if t.strip()), 1)
    return make_step(repo, plan.readme, first, "Overview", text)


def tests_step(plan) -> dict:
    text = f"Tests live in `{plan.test_dir}/`."
    if plan.test_cmd:
        text += f" Run them with `{plan.test_cmd}`."
    text += " Reading a test next to the module it covers is a quick way to see real inputs and outputs."
    return {"directory": plan.test_dir, "title": "Tests", "description": text}


def make_step(repo, path: str, line: int, title: str, description: str) -> dict:
    lines = repo.read(path) or []
    step = {"file": path, "line": int(line), "title": title, "description": description}
    if 1 <= line <= len(lines) and lines[line - 1].strip():
        step["pattern"] = pattern_for(lines[line - 1])
    return step


def static_tour(repo, plan, title: str = "", with_readme: bool = True, with_tests: bool = True) -> dict:
    steps = []
    if with_readme and plan.readme:
        steps.append(readme_step(plan, repo))
    total = len(plan.picks)
    for i, pick in enumerate(plan.picks):
        label = "Entry point" if i == 0 and pick.entry_reason else (pick.anchor_symbol or _short(pick.path))
        step_title = f"{label}: {_short(pick.path)}" if label != _short(pick.path) else label
        steps.append(make_step(repo, pick.path, pick.anchor_line, step_title, static_description(pick, i, total)))
    if with_tests and plan.test_dir:
        steps.append(tests_step(plan))
    return {
        "$schema": SCHEMA_URL,
        "title": title or f"Getting started with {plan.name}",
        "description": f"A guided walk from the entry point through the {total} files a newcomer needs first. Generated by amagi-codetour.",
        "isPrimary": True,
        "steps": steps,
    }


def write_tour(tour: dict, path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(tour, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return path


def load_tour(path) -> dict:
    text = Path(path).read_text(encoding="utf-8-sig")
    return json.loads(text)


def find_tours(root) -> list:
    root = Path(root)
    found = []
    for d in (root / ".tours", root / ".vscode" / "tours", root / ".github" / "tours"):
        if d.is_dir():
            found += sorted(d.glob("*.tour"))
    return found


def schema_errors(tour) -> list:
    """Checks the parts of the CodeTour JSON schema that matter for opening a tour."""
    errs = []
    if not isinstance(tour, dict):
        return ["tour is not a JSON object"]
    if not isinstance(tour.get("title"), str) or not tour.get("title"):
        errs.append("missing string `title`")
    steps = tour.get("steps")
    if not isinstance(steps, list):
        return errs + ["missing `steps` array"]
    for i, s in enumerate(steps, 1):
        if not isinstance(s, dict):
            errs.append(f"step {i}: not an object")
            continue
        if not isinstance(s.get("description"), str):
            errs.append(f"step {i}: missing string `description`")
        if "line" in s and (not isinstance(s["line"], (int, float)) or isinstance(s["line"], bool)):
            errs.append(f"step {i}: `line` must be a number")
        for key in ("file", "directory", "pattern", "title", "uri"):
            if key in s and not isinstance(s[key], str):
                errs.append(f"step {i}: `{key}` must be a string")
    return errs
